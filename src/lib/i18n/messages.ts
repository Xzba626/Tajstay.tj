/** Вложенные ключи через точку: "header.home" */
interface Tree {
  [key: string]: string | Tree;
}

function isTree(x: string | Tree): x is Tree {
  return typeof x === "object" && x !== null;
}

function pick(tree: Tree, path: string): string | undefined {
  const parts = path.split(".");
  let cur: string | Tree = tree;
  for (const p of parts) {
    if (!isTree(cur) || !(p in cur)) return undefined;
    cur = cur[p] as string | Tree;
  }
  return typeof cur === "string" ? cur : undefined;
}

