const byLocale: Record<Locale, Tree> = { ru, tg, en };

export function m(locale: Locale, path: string, vars?: Record<string, string | number>): string {
  let s = pick(byLocale[locale], path) ?? pick(ru, path) ?? path;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.replaceAll(`{${k}}`, String(v));
    }
  }
  return s;
}

/** Старый API для HotelCard / SearchBar */
export function tSearch(locale: Locale, key: keyof typeof searchKeys): string {
  const path = searchKeys[key];
  return m(locale, path);
}

